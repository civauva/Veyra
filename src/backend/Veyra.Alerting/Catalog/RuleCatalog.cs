    private static readonly Dictionary<string, CatalogRule> _byId = All.ToDictionary(rule => rule.Id);

    /// <summary>Finds a catalog rule by its name.</summary>
    /// <param name="id">The rule's name, such as <c>db-head-blocker</c>.</param>
    /// <returns>The rule, or <see langword="null"/> when it is not a catalog rule.</returns>
    public static CatalogRule? Find(string id) => _byId.GetValueOrDefault(id);

    /// <summary>Whether a catalog rule runs.</summary>
    /// <param name="rule">The rule.</param>
    /// <param name="settings">The Alerting settings.</param>
    /// <returns><see langword="true"/> unless switched off.</returns>
    public static bool Enabled(CatalogRule rule, AlertingOptions settings)
    {
        ArgumentNullException.ThrowIfNull(rule);
        ArgumentNullException.ThrowIfNull(settings);

        return Options(rule, settings)?.Enabled ?? true;
    }

    /// <summary>A catalog rule's caution and warning levels, in the measure's unit.</summary>
    /// <param name="rule">The rule.</param>
    /// <param name="settings">The Alerting settings.</param>
    /// <returns>The levels; no caution level for rules without one.</returns>
    public static (double? Caution, double Warning) Levels(CatalogRule rule, AlertingOptions settings)
    {
        ArgumentNullException.ThrowIfNull(rule);
        ArgumentNullException.ThrowIfNull(settings);

        var options = Options(rule, settings);
        var caution = options?.Caution is { } setCaution ? setCaution * rule.SettingScale : rule.DefaultCaution;
        var warning = options?.Warning is { } setWarning ? setWarning * rule.SettingScale : rule.DefaultWarning;

        return (rule.DefaultCaution is null ? null : caution, warning);
    }

    private static CatalogRuleOptions? Options(CatalogRule rule, AlertingOptions settings) =>
        settings.Catalog.GetValueOrDefault(rule.Setting);
}
