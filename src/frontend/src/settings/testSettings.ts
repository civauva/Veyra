import type { Setting, SettingsHistory, SettingsPage } from "../api/types";

/** A setting with sensible fields; tests override what they need. */
function setting(fields: Partial<Setting> & Pick<Setting, "key" | "section" | "group" | "label" | "kind">): Setting {
  return {
    help: `What ${fields.label.toLowerCase()} does.`,
    unit: null,
    minimum: null,
    maximum: null,
    choices: [],
    effect: "None",
    optional: false,
    advanced: false,
    environmentVariable: null,
    value: null,
    isSet: true,
    default: null,
    defaultSource: { kind: "code", name: null },
    saved: false,
    savedBy: null,
    savedAt: null,
    ...fields,
  };
}

